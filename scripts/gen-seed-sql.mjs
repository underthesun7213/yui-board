// Writes supabase/seed/fixtures.sql from tests/fixtures/*.json, so the local
// stack holds the same sample data the fixture mode shows. Local and CI only:
// production starts empty (Y-M4).
import { readFileSync, writeFileSync } from 'node:fs';

const read = (f) => JSON.parse(readFileSync(`tests/fixtures/${f}.json`, 'utf8'));
const places = read('places');
const events = read('events');
const occ = read('occurrences');
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const OWNER = '00000000-0000-4000-8000-0000000000f1';

const out = [
  '-- Generated by scripts/gen-seed-sql.mjs from tests/fixtures. Local and CI only.',
  `insert into auth.users (id, aud, role, is_anonymous, created_at, updated_at)
values ('${OWNER}', 'authenticated', 'authenticated', true, now(), now());`,
  `insert into app.accounts (user_id) values ('${OWNER}');`,
  '',
  'insert into app.places (id, name, category, description, gmaps_url, lat, lng, pref, lang) overriding system value values',
  places
    .map(
      (p) =>
        `  (${p.id}, ${q(p.name)}, ${q(p.category)}, ${q(p.description)}, ${q(p.gmaps_url)}, ${p.lat}, ${p.lng}, ${q(p.pref)}, ${q(p.lang)})`,
    )
    .join(',\n') + ';',
  `insert into app.place_owners (place_id, owner_id, client_token) select id, '${OWNER}', gen_random_uuid() from app.places;`,
  "select setval(pg_get_serial_sequence('app.places', 'id'), (select max(id) from app.places));",
  '',
  'insert into app.events (id, title, start_date, start_time, end_time, weekly_until, place_text, body, lang) overriding system value values',
  events
    .map(
      (e) =>
        `  (${e.id}, ${q(e.title)}, ${q(e.start_date)}, ${q(e.start_time)}, ${q(e.end_time)}, ${q(e.weekly_until)}, ${q(e.place_text)}, ${q(e.body)}, ${q(e.lang)})`,
    )
    .join(',\n') + ';',
  `insert into app.event_owners (event_id, owner_id, client_token) select id, '${OWNER}', gen_random_uuid() from app.events;`,
  "select setval(pg_get_serial_sequence('app.events', 'id'), (select max(id) from app.events));",
  '',
  'insert into app.event_occurrences (event_id, occurs_on, cancelled, title, start_time, end_time, place_text, body) values',
  occ
    .map(
      (o) =>
        `  (${o.event_id}, ${q(o.occurs_on)}, ${o.cancelled}, ${q(o.title)}, ${q(o.start_time)}, ${q(o.end_time)}, ${q(o.place_text)}, ${q(o.body)})`,
    )
    .join(',\n') + ';',
  '',
];
writeFileSync('supabase/seed/fixtures.sql', out.join('\n'));
console.log(`wrote supabase/seed/fixtures.sql (${places.length} places, ${events.length} events)`);
