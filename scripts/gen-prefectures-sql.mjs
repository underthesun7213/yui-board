// Writes supabase/migrations/…_prefectures.sql from the same boundary file the
// map draws (public/data/japan-prefectures.geojson), so the server judges a
// place's prefecture with the shapes people see. Rerun after changing the file.
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'supabase/migrations/20261013000040_prefectures.sql';
const geo = JSON.parse(readFileSync('public/data/japan-prefectures.geojson', 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = geo.features
  .map((f) => {
    const p = f.properties;
    const g = JSON.stringify(f.geometry);
    return `  (${q(p.c)}, ${q(p.ja)}, ${q(p.en)}, ${q(p.ko)}, ${q(g)})`;
  })
  .join(',\n');
if (geo.features.length !== 47)
  throw new Error(`expected 47 prefectures, got ${geo.features.length}`);

writeFileSync(
  OUT,
  `-- Generated by scripts/gen-prefectures-sql.mjs from public/data/japan-prefectures.geojson
-- (Natural Earth, public domain). Do not edit by hand.
create table app.prefectures (
  code char(2) primary key check (code ~ '^(0[1-9]|[1-3][0-9]|4[0-7])$'),
  name_ja text not null,
  name_en text not null,
  name_ko text not null,
  geom extensions.geography(MultiPolygon, 4326) not null
);
alter table app.prefectures enable row level security;

insert into app.prefectures (code, name_ja, name_en, name_ko, geom)
select code, name_ja, name_en, name_ko,
       extensions.st_multi(extensions.st_setsrid(extensions.st_geomfromgeojson(g), 4326))::extensions.geography
from (values
${rows}
) as v(code, name_ja, name_en, name_ko, g);

create index prefectures_geom on app.prefectures using gist (geom);
`,
);
console.log(`wrote ${OUT} (${geo.features.length} prefectures)`);
